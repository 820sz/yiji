/// 提示词。集中放在这里,方便按实际效果反复调,不用翻界面代码。
library;

/// 聊天页的 system 提示。
///
/// 定位不是通用助手,而是"读过你所有打卡记录的长期陪伴者":
/// 所以要求它先看数据再说话,并且不许空泛地夸。
const chatSystemPrompt = '''
你是「忆记」里的长期陪伴者,服务对象是一位大学生(写作、健身、英语学习、家教是他长期在推进的事)。

你的说话方式:
- 像一个熟悉他生活节奏的朋友,不说教、不打鸡血、不堆四字词和排比句。
- 他分享收获时,顺着具体内容往下聊,别只说"太棒了""很有意义"。
- 他状态差时,先承认这件事确实难受,再一起看能调整哪一步;不要急着给方案清单。
- 引用他过去的记录时,要具体到某天某件事,不编造没出现在数据里的细节。

回答用中文,长度跟着问题走:闲聊就短,他明确要分析时才展开。
''';

/// 生成周报/月报的指示。
///
/// 栏目名刻意对齐他 docx 里的固定结构(进度/不足/调整方向),
/// 生成的稿子能直接贴进他原来的文档,不用二次改写结构。
String reportPrompt({
  required String periodLabel,
  required String userContext,
}) {
  final name = userContext.trim().isEmpty ? '' : '他自称:$userContext。';
  return '''
根据下面这份真实打卡数据,写一份$periodLabel。

要求:
1. 用第一人称写,像他自己在总结,不要出现"数据显示""根据统计"这类旁观视角。
2. 按这个结构组织,小标题就用这三个:进度方面 / 不足 / 下周的调整方向
   (如果是月报,第三段改成"下个月的调整方向")。
3. 进度方面分「学习」「小说/创作」「生活/身体」「其他」几块写,哪块没内容就不写那块。
4. 完成率、具体天数这类数字要说出来,但要用自然的话说,不要罗列表格。
5. 不足这一栏,只写数据里真的能看出来的(比如反复没完成的事、记录断掉的天),
   不要臆造心理状态;确实看不出问题就写"这周没什么明显的问题"。
6. 调整方向要具体到可执行的动作,不要写"继续努力"这种空话。
7. 长度控制在 400 到 800 字,不要用 markdown 的加粗和列表符号,纯自然段。
8. 数据里每天的想法/收获是他自己写的原话,可以引用、可以顺着展开,但不要改写他的原意。

$name

--- 打卡数据 ---
''';
}

/// 把一句自然语言拆成"进度推进条"的字段。
///
/// 这份提示词存在的理由:用户建目标时不该被迫先想清楚"单位填什么、周期选哪个"。
/// 说一句「每周跑3次」就够了,拆解交给模型。
String goalParsePrompt() {
  return '''
你的任务:把用户随口说的一句目标,拆成结构化的字段。

用户可能说的是任何领域的事:跑步、读书、背单词、早睡、喝水、写代码、练琴……
不要假设是某一类任务,也不要把例子里的词套到用户身上。

字段说明:
- title:简短的目标名,2 到 6 个字,不含数字和周期(如「跑步」「读书」「背单词」)
- target:目标数值,必须是正数。用户说「一万」就是 10000,「3次」就是 3
- unit:计量单位(如「次」「公里」「页」「本」「小时」「杯」)。用户没明说时,
  按这件事最自然的计量方式来定;实在定不出来用「次」
- period:weekly(每周)、monthly(每月)或 custom(自定义)。默认 weekly
- direction:increase(想增加)或 decrease(想减少)。比如「体重降到59」是 decrease
- color:从这些里挑一个最贴的:yellow green blue orange pink purple graphite

如果用户那句话里根本读不出目标数值或目标事物,返回 {"ok": false}。

请只输出 JSON,不要任何解释文字。格式:
{
  "ok": true,
  "title": "跑步",
  "target": 3,
  "unit": "次",
  "period": "weekly",
  "direction": "increase",
  "color": "green"
}
''';
}

/// 把"完成的待办"匹配到"进度推进条"的指示。
///
/// 这份提示词的难点在于:**必须允许它说"匹配不上"**。
/// 如果逼它每条都给出数字,它会为了完成任务而硬凑,进度条就废了。
/// 所以反复强调"没有数字就跳过",并且要求理由里说清数字是怎么来的。
String goalMatchPrompt({
  required String goalsBlock,
  required String tasksBlock,
}) {
  return '''
你的任务:把"做完的事"对到"进度推进条"上,判断每条让它前进多少。

目标列表(每行:编号 | 名称 | 目标值 | 单位 | 周期):
$goalsBlock

做完的事(每行:编号 | 内容):
$tasksBlock

两种推进方式,要分清:

**一、待办里写明了数量** —— 按写明的量算。
比如"码字2k"→2000,"跑了5公里"→5,"刷了30个单词"→30。
写法很灵活("2k""2千""两千"都是 2000),按语义理解。

**二、待办里没写数量,但它本身就是这件事的一次** —— 算 1 个目标单位。
这是很常见的情况,不要漏掉:
- 目标是"力量训练 / 每周5次 / 次",待办是"下午 健身(胸+三头)" → 算 1 次
- 目标是"读书 / 每周3本 / 本",待办是"读完《义忆》" → 算 1 本
- 目标是"早起 / 每周5次 / 次",待办是"早上 7 点起床" → 算 1 次
判断依据是"这件事做了就等于目标推进了一个单位"。

判断规则:
1. 只有在待办和目标**确实是同一件事**时才匹配。拿不准就跳过。
   ("健身"能算进"力量训练";"家教备课"不能算进"力量训练"。)
2. **不要凭空编造数字。** 没有写明数量、又不属于"做一次就算一个单位"的,
   一律跳过。比如目标单位是"字",待办只写"码字"没写多少字,就跳过。
3. 一条待办最多匹配一个目标。
4. 单位不同但能合理换算就换算(如"40分钟"→按目标需要的单位折算);不能换算就跳过。
5. 方向为"减少"的目标(比如体重),amount 填**减少的量**(正数)。

reason 里要说清这个数字是怎么来的("待办写了2k""健身一次,算作一次力量训练")。

请只输出 JSON,不要任何解释文字。格式:
{
  "matches": [
    {"task": 1, "goal": 2, "amount": 2000, "reason": "待办写了码字2k,换算为2000字"},
    {"task": 3, "goal": 4, "amount": 1, "reason": "健身一次,算作一次力量训练"}
  ]
}

没有任何可匹配的项时,输出 {"matches": []}。
''';
}

/// 聊天页的 system 提示。
///
/// 定位是"陪他把事情往前推的人",不是通用助手。
///
/// 关于"记忆"的几条是这个提示词里最要紧的部分:他会把**当前这个对话**里
/// 说过的内容当成你的记忆,但你看不到其他对话、看不到他的记录——除非这次
/// 请求里明确附了数据。以前这里写的是"长期陪伴者,读过你所有打卡记录",
/// 模型于是顺着这句话编出他根本没记录过的事,他看到的就成了"AI 在凭空
/// 记得我"。所以现在反过来:没有数据就直说没有。
///
/// [memeHint] 非空时表示这次带了表情包图库,回复里可以按那个格式要一张。
String chatSystemPrompt({String memeHint = ''}) {
  return '''
你是「忆记」里的一个聊天伙伴。这个 app 里记录着他每天的任务、想法进度。

关于你记得什么,按这个来:
- 你能看到的只有**这个对话里已经说过的内容**。别的对话、他的记录,
  你都不知道,也不要假装知道。
- 如果这次消息里附了「打卡数据」,那就是他特意给你的,可以引用。
  没有附的时候,凡是你没在这个对话里听他说过的事,都不要提。
- 想知道他的情况就问;不要靠猜。"你上次说……""我记得你……"这种话,
  只有在这次对话里他真的说过的时候才能用。
- 他的记录里没有的细节(成绩、比赛、人际关系、身体状况),一律不编。

你的说话方式:
- 像一个熟悉他节奏的朋友,不说教、不打鸡血、不堆四字词和排比句。
- 他分享收获时,顺着具体内容往下聊,别只说"太棒了""很有意义"。
- 他状态差时,先承认这件事确实难受,再一起看能调整哪一步;不要急着给方案清单。

回答用中文,长度跟着问题走:闲聊就短,他明确要分析时才展开。
$memeHint''';
}

/// 允许发表情包时追加的那段说明。
///
/// 关键是**让它自己判断要不要发**,而不是每条都发:表情包是"接梗",
/// 用在每句话后面就成了刷屏。所以明确写出"不是每条都要发",并要求
/// 情绪词和画面描述分开填,好让它挑到贴题的那张。
///
/// 措辞上踩过一次坑:只写"想发的时候可以发""不是每句都要发",模型会理解成
/// "那就不发"——真实 API 上庆祝的场景它一次都没发。所以这里得**把该发的场景
/// 正面列出来**,并给一个例子,它才会真的动。
String memeHintPrompt(String tags) {
  return '''
【表情包功能】
你的界面里有一个表情包图库(「大肥鱼」那套),分类有:$tags。

要发图时,**在回复的最后另起一行**输出:
[表情: 情绪词 | 画面描述]

情绪词从上面几个里选(写"开心""无语""累"这种中文也行,系统会自己对应);
画面描述写你想要的画面,比如"瘫着不动""比心""蹦起来"。

什么时候输出这一行:
- 他分享做成了一件事、很爽很兴奋 → 输出
- 他吐槽、抱怨、说累 → 输出
- 他自嘲、开玩笑、跟你逗 → 输出
- 他在难过、需要安慰 → 输出
- 他在让你做具体分析(整理周报、复盘数据)、或只是平淡确认 → 不输出

一条回复最多一张。正文照常写完整,这一行加在最后,不占正文的位置。

示例——他说「哈哈我今天终于把那一章写完了,爽!」,
你的回复最后要有这样一行:
[表情: 开心 | 写完了超爽蹦起来]
''';
}

/// 生成周报/月报的指示。
///
/// 栏目名刻意对齐他 docx 里的固定结构(进度/不足/调整方向),
/// 生成的稿子能直接贴进他原来的文档,不用二次改写结构。
String reportPrompt({
  required String periodLabel,
  required String userContext,
}) {
  final name = userContext.trim().isEmpty ? '' : '他自称:$userContext。';
  return '''
根据下面这份真实打卡数据,写一份$periodLabel。

要求:
1. 用第一人称写,像他自己在总结,不要出现"数据显示""根据统计"这类旁观视角。
2. 按这个结构组织,小标题就用这三个:进度方面 / 不足 / 下周的调整方向
   (如果是月报,第三段改成"下个月的调整方向")。
3. 进度方面分「学习」「小说/创作」「生活/身体」「其他」几块写,哪块没内容就不写那块。
4. 完成率、具体天数这类数字要说出来,但要用自然的话说,不要罗列表格。
5. 不足这一栏,只写数据里真的能看出来的(比如反复没完成的事、记录断掉的天),
   不要臆造心理状态;确实看不出问题就写"这周没什么明显的问题"。
6. 调整方向要具体到可执行的动作,不要写"继续努力"这种空话。
7. 长度控制在 400 到 800 字,不要用 markdown 的加粗和列表符号,纯自然段。
8. 数据里每天的想法/收获是他自己写的原话,可以引用、可以顺着展开,但不要改写他的原意。

$name

--- 打卡数据 ---
''';
}

/// 把一句自然语言拆成"进度推进条"的字段。
///
/// 这份提示词存在的理由:用户建目标时不该被迫先想清楚"单位填什么、周期选哪个"。
/// 说一句「每周跑3次」就够了,拆解交给模型。
///
/// [target] 与 [unit] 都是**可填项**:说不清要到多少的目标照样能建,
/// 那时候它只是一条记录推进方向的推进条。所以这里绝不能用"读不出数值就失败"
/// 把这类目标挡在门外——那正是用户说"目标值不是必须的"时的意思。
String goalParsePrompt() {
  return '''
你的任务:把用户随口说的一句目标,拆成结构化的字段。

用户可能说的是任何领域的事:跑步、读书、背单词、早睡、喝水、写代码、练琴……
不要假设是某一类任务,也不要把例子里的词套到用户身上。

字段说明:
- title:简短的目标名,2 到 8 个字,不含数字和周期(如「跑步」「读书」「背单词」)。
  这是唯一必填的字段。
- target:目标数值,**只有用户明确说了数量才填**(「一万」是 10000,「3次」是 3)。
  用户没说数量就不要填这个字段——留空是完全正常的,不要为了凑数编一个。
- unit:计量单位(如「次」「公里」「页」「本」「小时」「杯」)。用户没明说时,
  按这件事最自然的计量方式来定,后面 AI 统计进度时会用到它。
- period:weekly(每周)、monthly(每月)或 custom(自定义),没说就 weekly
- direction:increase(想增加)或 decrease(想减少)。比如「体重降到59」是 decrease
- color:从这些里挑一个最贴的:yellow green blue orange pink purple graphite

只要读得出他在为什么事努力就返回 ok: true;target 该缺就缺。
只有连"这件事是什么"都读不出来(比如只输入了一串标点)才返回 {"ok": false}。

请只输出 JSON,不要任何解释文字。格式:
{
  "ok": true,
  "title": "跑步",
  "target": 3,
  "unit": "次",
  "period": "weekly",
  "direction": "increase",
  "color": "green"
}

用户没提数量时就是这样(注意没有 target):
{
  "ok": true,
  "title": "读《义忆》",
  "unit": "页",
  "period": "weekly",
  "direction": "increase",
  "color": "blue"
}
''';
}

/// 把"做完的事"匹配到"进度推进条"的指示。
///
/// 这份提示词的难点在于:**必须允许它说"匹配不上"**。
/// 如果逼它每条都给出数字,它会为了完成任务而硬凑,进度条就废了。
/// 所以反复强调"确实推进了才写",并且要求理由里说清数字是怎么来的。
///
/// 这里**故意不举具体领域的例子**。以前写的是「健身(胸+三头)→力量训练算1次」,
/// 结果模型把例子当成了规则本身:遇到别的领域就只会照搬那几个词,用户也以为
/// 每个新目标都得回头补一条说明。真正要它做的是语义判断——一件事属不属于
/// 某个目标的范围、里面提到的量是多少——那是概念,不是词表。
String goalMatchPrompt({
  required String goalsBlock,
  required String tasksBlock,
  bool suggestNewGoals = true,
}) {
  final newGoalRules = suggestNewGoals
      ? '''

另外,如果他做完的事里有一些**明显值得追踪、但上面没有对应推进条**的,
放到 "newGoals" 里问他一句要不要补上:
- 每条给出 title(简短名字,2 到 8 个字)与 unit(计量单位)。
- 一条待办只能出现在一个地方:已经算进上面某条推进条的,不要再放进 newGoals。
- 只在他**重复在做同类的事**、或者明显是长期在做的事时才建议。
  一次性的小事(取快递、交作业)不要建议建目标,否则他每次都会收到一堆噪音。
- 没有值得补的就给空数组,不要为了凑数硬提。'''
      : '';

  return '''
你的任务:阅读用户已经做完的事,判断每件事让他的哪条"推进条"前进了多少。

推进条(每行:编号 | 名称 | 目标值 | 单位 | 周期):
$goalsBlock

做完的事(每行:编号 | 内容):
$tasksBlock

判断一件事是否推进了某条推进条,靠的是**意思**,不是字面:
就算待办和目标一个词都没重合也能匹配,只要这件事做了就是在朝那个方向走。
反过来,字面相近但实际无关的(比如目标「学英语」和待办「看英文字幕的电影」)
不要硬算——这类要跳过。

推进量这样定:
- 待办里写明了数量就按写明的算。写法很自由,按语义理解:
  "2k""2千""两千"都是 2000;"半小时""30min"都是 30 分钟(单位是分钟时)。
- 没写明数量时,**只有当这条推进条的单位是"次数"时才记 1**。
  · 算"次数"的单位:次 / 回 / 遍 / 本 / 顿 / 杯 / 个 / 首 / 章 这类**可以数出来的事**。
    例:目标是「跑步 · 每周3次」,待办写「晚上跑步」→ 记 1 次。
  · 算"量"的单位:字 / 页 / 公里 / 米 / 分钟 / 小时 / 元 / 千克 这类**要么给出数字、
    要么就说不清的量**。这种情况**必须跳过**,绝不能记成 1。
    例:目标是「小说推进 · 每周1万字」,待办只写「码字」→ **跳过**。
    记成"1 字"是错的:一次码字不可能只推进一个字,那是编出来的数字。
- 用最自然的单位记。目标已经定了单位就换成那个单位;换算不了就跳过。

**宁可一条都不给,也不要为了凑数写一个数。** 用户会照着你的数字判断自己有没有在推进,
一个编出来的数字比漏掉一条更糟——他会以为那件事只值那么多。

unit 字段填你这次用的计量单位(如 页/次/公里/分钟/字)。它有两个用处:
用户当初没给这条推进条定单位时用它补上,定了就是给用户核对。

另外记住:推进条不一定要有目标值。目标值是「未设定」时,你更要照常判断——
用户就是想让你告诉他这些天到底推进了多少,而不是等他先定个数才肯动。

只有确实推进了才写,拿不准就跳过。一条待办最多匹配一条推进条。
方向是减少的(比如体重),amount 填减少的量,正数。

reason 里用一句人话说清这个数字是怎么来的,用户要靠它核对你的判断。$newGoalRules

请只输出 JSON,不要任何解释文字。格式:
{
  "matches": [
    {"task": 1, "goal": 2, "amount": 30, "unit": "页", "reason": "待办里写了读到第 30 页"}
  ],
  "newGoals": [
    {"task": 5, "title": "读书", "unit": "页", "reason": "这周读了三次书,但你没在追踪它"}
  ]
}

没有任何可匹配的项时,输出 {"matches": [], "newGoals": []}。
''';
}
